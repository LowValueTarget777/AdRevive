"""Bake the original ADgame art into textures supported by UE's runtime image importer."""
from pathlib import Path
from PIL import Image, ImageDraw

root = Path(__file__).resolve().parent
mod = root.parent / "Mods" / "AdRevive"
out = mod / "Art"
out.mkdir(exist_ok=True)
index = []
for i, src in enumerate(sorted((root / "src/assets/units").glob("*.webp"))):
    img = Image.open(src).convert("RGBA")
    img.thumbnail((144, 144), Image.Resampling.LANCZOS)
    square = Image.new("RGBA", (144, 144))
    square.alpha_composite(img, ((144 - img.width) // 2, (144 - img.height) // 2))
    name = f"unit-{i:03d}.png"
    square.save(out / name, optimize=True)
    index.append(f'    ["{src.stem}"] = "{name}",')
(mod / "Scripts/adart.lua").write_text("-- Generated by ADgame/build_art.py\nreturn {\n" + "\n".join(index) + "\n}\n", encoding="utf-8")

mountains = Image.open(root / "src/assets/mountains.jpg").convert("RGB")
w, h = mountains.size
mountains = mountains.crop((round(w*.24), 0, round(w*.90), h)).resize((620, 765), Image.Resampling.LANCZOS)
paper = Image.blend(Image.new("RGB", mountains.size, "#ded3b6"), mountains, .52)
draw = ImageDraw.Draw(paper, "RGBA")
stops = [(0,(226,212,178,46)),(.28,(229,216,187,173)),(.73,(217,206,179,202)),(1,(188,179,153,96))]
for y in range(765):
    t = y/764
    for (a, lo), (b, hi) in zip(stops, stops[1:]):
        if a <= t <= b:
            draw.line((0,y,619,y), fill=tuple(round(x+(z-x)*(t-a)/(b-a)) for x,z in zip(lo,hi)))
            break
draw.rectangle((0,0,309,764),fill=(202,166,97,18))
draw.rectangle((310,0,619,764),fill=(164,87,69,16))
for y in range(53,630,15): draw.line((310,y,310,y+6),fill=(103,94,72,140))
for x in range(18,602,12): draw.line((x,640,x+3,640),fill=(99,87,65,104))
for x in (155,465):
    draw.rectangle((x-54,18,x+54,55),fill=(230,219,190,212))
    draw.line((x-54,55,x+54,55),fill="#816e50",width=2)
paper.save(out / "ground.png", optimize=True)
